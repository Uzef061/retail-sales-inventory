import 'package:flutter/material.dart';
import 'package:flutter/services.dart';
import '../../core/services/report_service.dart';
import '../../core/theme/app_theme.dart';
import '../../models/report_data.dart';
import 'profit_loss_screen.dart';

class ReportsScreen extends StatefulWidget {
  const ReportsScreen({super.key});

  @override
  State<ReportsScreen> createState() => _ReportsScreenState();
}

class _ReportsScreenState extends State<ReportsScreen> with SingleTickerProviderStateMixin {
  final _reportService = ReportService();
  late TabController _tabController;

  String _selectedRange = 'month'; // 'today', 'week', 'month', 'all'
  bool _isLoading = true;
  String? _errorMessage;
  ReportData? _reportData;

  @override
  void initState() {
    super.initState();
    _tabController = TabController(length: 4, vsync: this);
    _loadReport();
  }

  @override
  void dispose() {
    _tabController.dispose();
    super.dispose();
  }

  Future<void> _loadReport() async {
    setState(() {
      _isLoading = true;
      _errorMessage = null;
    });

    try {
      final data = await _reportService.getComprehensiveReport(timeRange: _selectedRange);
      setState(() {
        _reportData = data;
        _isLoading = false;
      });
    } catch (e) {
      setState(() {
        _errorMessage = 'Could not load report: $e';
        _isLoading = false;
      });
    }
  }

  void _shareReportSummary() {
    if (_reportData == null) return;
    final r = _reportData!;
    final summary = '''
📊 BUSINESS REPORT SUMMARY (${_selectedRange.toUpperCase()})
━━━━━━━━━━━━━━━━━━━━
💰 Sales Revenue: Rs ${r.totalSales.toStringAsFixed(0)} (${r.totalOrders} orders)
📦 Inventory Value: Rs ${r.inventoryValue.toStringAsFixed(0)} (${r.totalProducts} items)
⚠️ Low Stock Alert: ${r.lowStockCount} items
🚚 Purchases: Rs ${r.totalPurchases.toStringAsFixed(0)}
👥 Customers Balance: Rs ${r.receivables.toStringAsFixed(0)} (Receivables)
🏢 Suppliers Balance: Rs ${r.payables.toStringAsFixed(0)} (Payables)
━━━━━━━━━━━━━━━━━━━━
Generated by Retail Sales & Inventory Management
''';

    Clipboard.setData(ClipboardData(text: summary));
    ScaffoldMessenger.of(context).showSnackBar(
      const SnackBar(
        content: Text('Report summary copied to clipboard! Ready to share.'),
        backgroundColor: AppTheme.success,
      ),
    );
  }

  @override
  Widget build(BuildContext context) {
    return Scaffold(
      appBar: AppBar(
        title: const Text('Business Reports'),
        actions: [
          IconButton(
            icon: const Icon(Icons.share_outlined),
            tooltip: 'Copy Report Summary',
            onPressed: _reportData == null ? null : _shareReportSummary,
          ),
          IconButton(
            icon: const Icon(Icons.refresh),
            tooltip: 'Refresh',
            onPressed: _loadReport,
          ),
        ],
        bottom: PreferredSize(
          preferredSize: const Size.fromHeight(100),
          child: Column(
            children: [
              // Date Filter Chips
              Container(
                padding: const EdgeInsets.symmetric(horizontal: 16, vertical: 6),
                color: AppTheme.surface,
                child: Row(
                  mainAxisAlignment: MainAxisAlignment.spaceAround,
                  children: [
                    _buildRangeChip('today', 'Today'),
                    _buildRangeChip('week', 'This Week'),
                    _buildRangeChip('month', 'This Month'),
                    _buildRangeChip('all', 'All Time'),
                  ],
                ),
              ),
              TabBar(
                controller: _tabController,
                isScrollable: true,
                indicatorColor: AppTheme.primary,
                labelColor: AppTheme.primary,
                unselectedLabelColor: AppTheme.textSecondary,
                tabs: const [
                  Tab(icon: Icon(Icons.point_of_sale, size: 20), text: 'Sales'),
                  Tab(icon: Icon(Icons.inventory_2_outlined, size: 20), text: 'Inventory'),
                  Tab(icon: Icon(Icons.shopping_cart_outlined, size: 20), text: 'Purchases'),
                  Tab(icon: Icon(Icons.account_balance_wallet_outlined, size: 20), text: 'Ledger'),
                ],
              ),
            ],
          ),
        ),
      ),
      body: _isLoading
          ? const Center(child: CircularProgressIndicator(color: AppTheme.primary))
          : _errorMessage != null
              ? Center(
                  child: Padding(
                    padding: const EdgeInsets.all(24),
                    child: Column(
                      mainAxisSize: MainAxisSize.min,
                      children: [
                        const Icon(Icons.error_outline, size: 48, color: AppTheme.error),
                        const SizedBox(height: 12),
                        Text(_errorMessage!, textAlign: TextAlign.center),
                        const SizedBox(height: 16),
                        ElevatedButton(onPressed: _loadReport, child: const Text('Retry')),
                      ],
                    ),
                  ),
                )
              : TabBarView(
                  controller: _tabController,
                  children: [
                    _buildSalesTab(),
                    _buildInventoryTab(),
                    _buildPurchasesTab(),
                    _buildLedgerTab(),
                  ],
                ),
    );
  }

  Widget _buildRangeChip(String range, String label) {
    final isSel = _selectedRange == range;
    return ChoiceChip(
      label: Text(label),
      selected: isSel,
      onSelected: (selected) {
        if (selected) {
          setState(() => _selectedRange = range);
          _loadReport();
        }
      },
      selectedColor: AppTheme.primary,
      labelStyle: TextStyle(
        fontSize: 12,
        fontWeight: isSel ? FontWeight.bold : FontWeight.normal,
        color: isSel ? Colors.white : AppTheme.textPrimary,
      ),
      showCheckmark: false,
    );
  }

  // --- TAB 1: SALES REPORT ---
  Widget _buildSalesTab() {
    final r = _reportData!;
    return RefreshIndicator(
      onRefresh: _loadReport,
      child: ListView(
        padding: const EdgeInsets.all(16),
        children: [
          // Banner to jump to P&L
          Card(
            color: AppTheme.primaryLight,
            elevation: 0,
            shape: RoundedRectangleBorder(
              borderRadius: BorderRadius.circular(12),
              side: BorderSide(color: AppTheme.primary.withValues(alpha: 0.2)),
            ),
            child: ListTile(
              leading: const Icon(Icons.analytics_outlined, color: AppTheme.primary),
              title: const Text('View Full Profit & Loss Report', style: TextStyle(fontWeight: FontWeight.bold, fontSize: 14)),
              subtitle: const Text('Detailed margins, COGS & net income', style: TextStyle(fontSize: 12)),
              trailing: const Icon(Icons.chevron_right, color: AppTheme.primary),
              onTap: () {
                Navigator.of(context).push(MaterialPageRoute(builder: (_) => const ProfitLossScreen()));
              },
            ),
          ),
          const SizedBox(height: 16),

          // Overview KPI cards
          Row(
            children: [
              Expanded(
                child: _buildMetricCard(
                  'Total Sales',
                  'Rs ${r.totalSales.toStringAsFixed(0)}',
                  Icons.trending_up,
                  AppTheme.success,
                ),
              ),
              const SizedBox(width: 12),
              Expanded(
                child: _buildMetricCard(
                  'Total Orders',
                  '${r.totalOrders}',
                  Icons.receipt_long,
                  AppTheme.primary,
                ),
              ),
            ],
          ),
          const SizedBox(height: 12),
          Row(
            children: [
              Expanded(
                child: _buildMetricCard(
                  'Average Order',
                  'Rs ${r.avgOrderValue.toStringAsFixed(0)}',
                  Icons.calculate_outlined,
                  AppTheme.secondary,
                ),
              ),
              const SizedBox(width: 12),
              Expanded(
                child: _buildMetricCard(
                  'Cash Collected',
                  'Rs ${r.cashCollected.toStringAsFixed(0)}',
                  Icons.payments_outlined,
                  AppTheme.success,
                ),
              ),
            ],
          ),
          const SizedBox(height: 24),

          // Top Selling Products
          const Text(
            'TOP SELLING PRODUCTS',
            style: TextStyle(fontSize: 12, fontWeight: FontWeight.bold, color: AppTheme.textMuted, letterSpacing: 0.8),
          ),
          const SizedBox(height: 8),
          if (r.bestSellers.isEmpty)
            Card(
              child: Padding(
                padding: const EdgeInsets.all(24),
                child: Center(
                  child: Text('No product sales recorded in this period', style: TextStyle(color: AppTheme.textSecondary)),
                ),
              ),
            )
          else
            ...r.bestSellers.map((item) => Card(
                  margin: const EdgeInsets.only(bottom: 8),
                  child: ListTile(
                    leading: CircleAvatar(
                      backgroundColor: AppTheme.primaryLight,
                      child: Text(
                        item.name.isNotEmpty ? item.name[0].toUpperCase() : 'P',
                        style: const TextStyle(fontWeight: FontWeight.bold, color: AppTheme.primary),
                      ),
                    ),
                    title: Text(item.name, style: const TextStyle(fontWeight: FontWeight.bold, fontSize: 14)),
                    subtitle: Text('${item.category} • ${item.unitsSold} units sold', style: const TextStyle(fontSize: 12)),
                    trailing: Text(
                      'Rs ${item.sales.toStringAsFixed(0)}',
                      style: const TextStyle(fontWeight: FontWeight.bold, fontSize: 14, color: AppTheme.primary),
                    ),
                  ),
                )),
        ],
      ),
    );
  }

  // --- TAB 2: INVENTORY REPORT ---
  Widget _buildInventoryTab() {
    final r = _reportData!;
    return RefreshIndicator(
      onRefresh: _loadReport,
      child: ListView(
        padding: const EdgeInsets.all(16),
        children: [
          Row(
            children: [
              Expanded(
                child: _buildMetricCard(
                  'Stock Valuation',
                  'Rs ${r.inventoryValue.toStringAsFixed(0)}',
                  Icons.account_balance,
                  AppTheme.primary,
                ),
              ),
              const SizedBox(width: 12),
              Expanded(
                child: _buildMetricCard(
                  'Total Products',
                  '${r.totalProducts}',
                  Icons.inventory_2,
                  AppTheme.secondary,
                ),
              ),
            ],
          ),
          const SizedBox(height: 12),
          Row(
            children: [
              Expanded(
                child: _buildMetricCard(
                  'Low Stock Alerts',
                  '${r.lowStockCount}',
                  Icons.warning_amber_rounded,
                  r.lowStockCount > 0 ? AppTheme.warning : AppTheme.success,
                ),
              ),
              const SizedBox(width: 12),
              Expanded(
                child: _buildMetricCard(
                  'Out of Stock',
                  '${r.outOfStockCount}',
                  Icons.error_outline,
                  r.outOfStockCount > 0 ? AppTheme.error : AppTheme.success,
                ),
              ),
            ],
          ),
          const SizedBox(height: 24),

          // Low Stock Alert items list
          Text(
            'ATTENTION REQUIRED (${r.lowStockProducts.length})',
            style: const TextStyle(fontSize: 12, fontWeight: FontWeight.bold, color: AppTheme.textMuted, letterSpacing: 0.8),
          ),
          const SizedBox(height: 8),
          if (r.lowStockProducts.isEmpty)
            Card(
              child: Padding(
                padding: const EdgeInsets.all(24),
                child: Center(
                  child: Row(
                    mainAxisAlignment: MainAxisAlignment.center,
                    children: const [
                      Icon(Icons.check_circle_outline, color: AppTheme.success, size: 20),
                      SizedBox(width: 8),
                      Text('All products have healthy stock levels!', style: TextStyle(color: AppTheme.success, fontWeight: FontWeight.w600)),
                    ],
                  ),
                ),
              ),
            )
          else
            ...r.lowStockProducts.map((p) => Card(
                  margin: const EdgeInsets.only(bottom: 8),
                  child: ListTile(
                    leading: const CircleAvatar(
                      backgroundColor: Color(0xFFFEF3C7),
                      child: Icon(Icons.priority_high, color: AppTheme.warning, size: 20),
                    ),
                    title: Text(p['name']?.toString() ?? 'Product', style: const TextStyle(fontWeight: FontWeight.bold, fontSize: 14)),
                    subtitle: Text('SKU: ${p['sku'] ?? 'N/A'} • Cost: Rs ${p['cost'] ?? 0}'),
                    trailing: Container(
                      padding: const EdgeInsets.symmetric(horizontal: 10, vertical: 4),
                      decoration: BoxDecoration(
                        color: (p['stock'] ?? 0) == 0 ? const Color(0xFFFEE2E2) : const Color(0xFFFEF3C7),
                        borderRadius: BorderRadius.circular(8),
                      ),
                      child: Text(
                        '${p['stock'] ?? 0} left',
                        style: TextStyle(
                          fontSize: 12,
                          fontWeight: FontWeight.bold,
                          color: (p['stock'] ?? 0) == 0 ? AppTheme.error : const Color(0xFFB45309),
                        ),
                      ),
                    ),
                  ),
                )),
        ],
      ),
    );
  }

  // --- TAB 3: PURCHASES REPORT ---
  Widget _buildPurchasesTab() {
    final r = _reportData!;
    return RefreshIndicator(
      onRefresh: _loadReport,
      child: ListView(
        padding: const EdgeInsets.all(16),
        children: [
          Row(
            children: [
              Expanded(
                child: _buildMetricCard(
                  'Total Purchases',
                  'Rs ${r.totalPurchases.toStringAsFixed(0)}',
                  Icons.shopping_cart_checkout,
                  AppTheme.secondary,
                ),
              ),
              const SizedBox(width: 12),
              Expanded(
                child: _buildMetricCard(
                  'Purchase Orders',
                  '${r.purchaseOrdersCount}',
                  Icons.receipt,
                  AppTheme.primary,
                ),
              ),
            ],
          ),
          const SizedBox(height: 24),

          const Text(
            'PURCHASE SUMMARY INSIGHTS',
            style: TextStyle(fontSize: 12, fontWeight: FontWeight.bold, color: AppTheme.textMuted, letterSpacing: 0.8),
          ),
          const SizedBox(height: 8),
          Card(
            child: Padding(
              padding: const EdgeInsets.all(16),
              child: Column(
                children: [
                  _buildSummaryRow('Total Suppliers Sourced', '${r.suppliersCount}'),
                  const Divider(),
                  _buildSummaryRow('Average PO Value', 'Rs ${(r.purchaseOrdersCount > 0 ? r.totalPurchases / r.purchaseOrdersCount : 0).toStringAsFixed(0)}'),
                  const Divider(),
                  _buildSummaryRow('Outstanding to Suppliers', 'Rs ${r.payables.toStringAsFixed(0)}'),
                ],
              ),
            ),
          ),
        ],
      ),
    );
  }

  // --- TAB 4: LEDGER & BALANCES ---
  Widget _buildLedgerTab() {
    final r = _reportData!;
    final netLedger = r.receivables - r.payables;
    return RefreshIndicator(
      onRefresh: _loadReport,
      child: ListView(
        padding: const EdgeInsets.all(16),
        children: [
          Row(
            children: [
              Expanded(
                child: _buildMetricCard(
                  'Receivables (Customers)',
                  'Rs ${r.receivables.toStringAsFixed(0)}',
                  Icons.call_received,
                  AppTheme.success,
                ),
              ),
              const SizedBox(width: 12),
              Expanded(
                child: _buildMetricCard(
                  'Payables (Suppliers)',
                  'Rs ${r.payables.toStringAsFixed(0)}',
                  Icons.call_made,
                  AppTheme.error,
                ),
              ),
            ],
          ),
          const SizedBox(height: 16),

          Card(
            color: netLedger >= 0 ? const Color(0xFFF0FDF4) : const Color(0xFFFEF2F2),
            elevation: 0,
            shape: RoundedRectangleBorder(
              borderRadius: BorderRadius.circular(14),
              side: BorderSide(color: (netLedger >= 0 ? AppTheme.success : AppTheme.error).withValues(alpha: 0.3)),
            ),
            child: Padding(
              padding: const EdgeInsets.all(18),
              child: Column(
                crossAxisAlignment: CrossAxisAlignment.start,
                children: [
                  Row(
                    mainAxisAlignment: MainAxisAlignment.spaceBetween,
                    children: [
                      const Text(
                        'NET BUSINESS POSITION',
                        style: TextStyle(fontSize: 12, fontWeight: FontWeight.bold, color: AppTheme.textSecondary, letterSpacing: 0.8),
                      ),
                      Icon(
                        netLedger >= 0 ? Icons.check_circle : Icons.warning_rounded,
                        color: netLedger >= 0 ? AppTheme.success : AppTheme.error,
                        size: 20,
                      ),
                    ],
                  ),
                  const SizedBox(height: 8),
                  Text(
                    '${netLedger >= 0 ? '+' : ''}Rs ${netLedger.toStringAsFixed(0)}',
                    style: TextStyle(
                      fontSize: 26,
                      fontWeight: FontWeight.w900,
                      color: netLedger >= 0 ? AppTheme.success : AppTheme.error,
                    ),
                  ),
                  const SizedBox(height: 6),
                  Text(
                    netLedger >= 0
                        ? 'Your customers owe you more than what you owe suppliers.'
                        : 'Your supplier payables exceed your customer receivables.',
                    style: const TextStyle(fontSize: 12, color: AppTheme.textSecondary),
                  ),
                ],
              ),
            ),
          ),
        ],
      ),
    );
  }

  Widget _buildMetricCard(String label, String value, IconData icon, Color color) {
    return Card(
      child: Padding(
        padding: const EdgeInsets.all(16),
        child: Column(
          crossAxisAlignment: CrossAxisAlignment.start,
          children: [
            Row(
              mainAxisAlignment: MainAxisAlignment.spaceBetween,
              children: [
                Flexible(
                  child: Text(
                    label,
                    style: const TextStyle(fontSize: 12, color: AppTheme.textSecondary, fontWeight: FontWeight.w500),
                    overflow: TextOverflow.ellipsis,
                  ),
                ),
                Icon(icon, size: 20, color: color),
              ],
            ),
            const SizedBox(height: 8),
            Text(
              value,
              style: TextStyle(fontSize: 18, fontWeight: FontWeight.bold, color: color),
            ),
          ],
        ),
      ),
    );
  }

  Widget _buildSummaryRow(String label, String val) {
    return Padding(
      padding: const EdgeInsets.symmetric(vertical: 8),
      child: Row(
        mainAxisAlignment: MainAxisAlignment.spaceBetween,
        children: [
          Text(label, style: const TextStyle(fontSize: 13, color: AppTheme.textSecondary)),
          Text(val, style: const TextStyle(fontSize: 14, fontWeight: FontWeight.bold, color: AppTheme.textPrimary)),
        ],
      ),
    );
  }
}
